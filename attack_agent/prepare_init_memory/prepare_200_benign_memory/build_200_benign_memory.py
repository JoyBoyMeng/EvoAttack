RESULT_HEADER = [
    "agent",
    "task_index",
    "attack_tool_index",
    "attack_tool",
    "tools_used",
    "original_success",
    "api_failed",
    "row_elapsed_seconds",
]


def _json_names(names: Iterable[str]) -> str:
    return json.dumps(sorted(set(names)), ensure_ascii=False, separators=(",", ":"))


def _memory_payload(
    *,
    memory_id: str,
    memory_text: str,
    metadata: Mapping[str, Any],
    user_id: str,
    agent_id: str,
) -> dict[str, Any]:
    now = datetime.now(timezone.utc).isoformat()
    payload = dict(metadata)
    payload.update(
        {
            "user_id": user_id,
            "agent_id": agent_id,
            "role": "user",
            "data": memory_text,
            "hash": hashlib.md5(memory_text.encode("utf-8")).hexdigest(),
            "created_at": now,
            "updated_at": now,
            "text_lemmatized": memory_text,
        }
    )
    payload.setdefault("memory_id", memory_id)
    return payload


class TemplateEmbeddingMemoryWriter:
    """Mem0-compatible writer that decouples stored text from embedded text."""

    def __init__(
        self,
        *,
        base_adapter: Any,
        normal_tool_names: Iterable[str],
        embedding_model_name: str,
    ) -> None:
        self.memory = base_adapter.memory
        self.user_id = base_adapter.user_id
        self.agent_id = base_adapter.agent_id
        self.namespace = base_adapter.namespace
        self.normal_tool_names = frozenset(normal_tool_names)
        self.embedding_model_name = embedding_model_name
        self._last_sequence_ns = 0

        if len(self.normal_tool_names) != 2:
            raise ValueError(
                "A benign init probe must have exactly two normal tools; "
                f"found {sorted(self.normal_tool_names)!r}."
            )

    def _next_sequence_ns(self) -> int:
        sequence = max(time.time_ns(), self._last_sequence_ns + 1)
        self._last_sequence_ns = sequence
        return sequence

    def add_texts(
        self,
        texts: Iterable[str] | str,
        metadatas: Iterable[Mapping[str, Any]] | None = None,
        ids: Iterable[str] | None = None,
        **_: Any,
    ) -> list[dict[str, Any]]:
        text_list = [texts] if isinstance(texts, str) else list(texts)
        metadata_list = list(metadatas or ({} for _ in text_list))
        id_list = list(ids) if ids is not None else [str(uuid.uuid4()) for _ in text_list]
        if not (len(text_list) == len(metadata_list) == len(id_list)):
            raise ValueError("texts, metadatas, and ids must have the same length")

        results: list[dict[str, Any]] = []
        vector_store = self.memory.vector_store
        embedding_model = self.memory.embedding_model
        for memory_id, memory_text, raw_metadata in zip(
            id_list, text_list, metadata_list
        ):
            metadata = dict(raw_metadata)
            task = str(metadata.pop("_embedding_task", "")).strip()
            if not task:
                raise ValueError("Missing private _embedding_task metadata")
            construction_started_at = metadata.pop(
                "_construction_started_perf_counter",
                None,
            )
            if construction_started_at is None:
                raise ValueError(
                    "Missing private _construction_started_perf_counter metadata"
                )
            construction_started_at = float(construction_started_at)

            tools_used = extract_tools_used(memory_text)
            if not tools_used:
                raise ValueError("Benign probe did not execute a recognizable normal tool")
            unexpected_tools = set(tools_used) - self.normal_tool_names
            if unexpected_tools:
                raise ValueError(
                    "Benign probe used a non-normal tool: "
                    f"{sorted(unexpected_tools)!r}"
                )

            attack_tool = str(metadata.get("attack_tool", "")).strip()
            if not attack_tool:
                raise ValueError("Missing attack_tool provenance label")
            available_tools = sorted(self.normal_tool_names | {attack_tool})
            if len(available_tools) != 3:
                raise ValueError(
                    "Expected two normal tools plus one distinct attack tool; "
                    f"found {available_tools!r}"
                )

            embedding_text = build_memory_embedding_text(
                task,
                available_tools,
                tools_used,
            )
            embedding = list(embedding_model.embed(embedding_text, "add"))
            if not embedding or not all(math.isfinite(float(value)) for value in embedding):
                raise ValueError("Embedding API returned an empty or non-finite vector")
            if not any(float(value) != 0.0 for value in embedding):
                raise ValueError("Embedding API returned an all-zero vector")

            metadata.update(
                {
                    "namespace": self.namespace,
                    "memory_sequence_ns": self._next_sequence_ns(),
                    "tools_used": _json_names(tools_used),
                    "available_tools": _json_names(available_tools),
                    "normal_tools": _json_names(self.normal_tool_names),
                    "attack_tool_exposed": 0,
                    "embedding_text": embedding_text,
                    "embedding_template_version": "task_available_tools_used_v2",
                    "embedding_model": self.embedding_model_name,
                }
            )
            payload = _memory_payload(
                memory_id=memory_id,
                memory_text=str(memory_text),
                metadata=metadata,
                user_id=self.user_id,
                agent_id=self.agent_id,
            )
            vector_store.insert(
                vectors=[embedding],
                ids=[memory_id],
                payloads=[payload],
            )
            memory_record = {
                "id": memory_id,
                "memory": str(memory_text),
                "metadata": payload,
            }
            construction_elapsed_seconds = time.perf_counter() - construction_started_at
            log_event(
                "BENIGN_INIT_MEMORY_CREATED",
                construction_elapsed_seconds=round(
                    construction_elapsed_seconds,
                    6,
                ),
                embedding_text=f"\n{embedding_text}",
                memory_record=json.dumps(
                    memory_record,
                    ensure_ascii=False,
                    indent=2,
                ),
            )
            results.append(
                {
                    "id": memory_id,
                    "memory": str(memory_text),
                    "event": "ADD",
                    "role": "user",
                }
            )
        return results

    def add_documents(self, documents: Iterable[Any], **kwargs: Any) -> list[Any]:
        documents = list(documents)
        return self.add_texts(
            [getattr(document, "page_content", str(document)) for document in documents],
            metadatas=[getattr(document, "metadata", {}) or {} for document in documents],
            **kwargs,
        )

    def persist(self) -> None:
        return None


