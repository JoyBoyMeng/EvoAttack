"""Build 200 benign target memories with template-derived embeddings.

Each record is generated by a fresh benign probe.  The target agent receives
only its two normal tools; the attack tool is retained as retrieval provenance
and is never exposed to the agent.  The full episode text is stored unchanged,
while its vector is computed from ``TASK``, ``AVAILABLE_TOOLS``, and the normal
tools actually present in ``TOOLS_USED``.
"""

